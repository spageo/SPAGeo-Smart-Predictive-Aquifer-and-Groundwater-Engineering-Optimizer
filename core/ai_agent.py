"""AI agent integration using GeoAgent framework."""

from qgis.PyQt.QtCore import QObject, pyqtSignal
from qgis.core import QgsMessageLog, QgsProject

# Import GeoAgent for QGIS
try:
    from geoagent import for_qgis

except ImportError:
    QgsMessageLog.logMessage(
        "GeoAgent not installed. Please install geoagent package.",
        "SPAGeo"
    )
    raise ImportError("GeoAgent required for AI integration")

class SPAGeoAgent(QObject):
    """SPAGeo AI agent using GeoAgent framework."""

    response_received = pyqtSignal(str)
    script_generated = pyqtSignal(str)
    error_occurred = pyqtSignal(str)

    def __init__(self, iface):
        """Initialize SPAGeo AI agent."""
        super().__init__()
        self.iface = iface
        self.agent = None
        self.supported_providers = [
            'openai'  # OpenAI (GPT-4, etc.)
            ]
        self.current_provider = 'openai'

    def initialize(self, provider: str = 'openai', api_key: str = None):
        """
        Initialize the AI agent with specified provider.

        Args:
            provider: AI provider ('openai', 'anthropic', 'google', 'bedrock', 'ollama')
            api_key: API key for the provider
        """
        if provider not in self.supported_providers:
            raise ValueError(f"Provider {provider} not supported")

        # Set environment variable for API key
        if api_key:
            import os
            if provider == 'openai':
                os.environ['OPENAI_API_KEY'] = api_key
         #   elif provider == 'anthropic':
         #       os.environ['ANTHROPIC_API_KEY'] = api_key
          #  elif provider == 'google':
          #      os.environ['GOOGLE_API_KEY'] = api_key

        # Initialize GeoAgent for QGIS
        self.agent = for_qgis(self.iface, provider=provider)
        self.current_provider = provider

        QgsMessageLog.logMessage(
            f"SPAGeo Agent initialized with {provider}",
            "SPAGeo"
        )

    def process_message(self, message: str) -> str:
        """
        Process a user message with the AI agent.

        Args:
            message: User message
            attachments: Optional images (screenshots, paste)

        Returns:
            str: AI response
        """
        if not self.agent:
            raise RuntimeError("Agent not initialized")

        try:
            # Process message with GeoAgent
            response = self.agent.chat(message)
            self.response_received.emit(response.answer_text)

            # Log success
            QgsMessageLog.logMessage(
                f"Agent processed message: {message[:50]}...",
                "SPAGeo"
            )

            return response.answer_text

        except Exception as e:
            error_msg = f"Agent error: {str(e)}"
            QgsMessageLog.logMessage(error_msg, "SPAGeo")
            self.error_occurred.emit(error_msg)
            raise

