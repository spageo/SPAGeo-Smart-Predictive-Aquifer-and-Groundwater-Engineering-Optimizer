    def get_project_context(self) -> dict:
        """
        Get current QGIS project context for AI.
        GeoAgent provides project inspection tools[citation:2].
        """
        context = {
            'layers': [],
            'active_layer': None,
            'project_path': None,
            'crs': None
        }

        # Get project information
        project = QgsProject.instance()
        context['project_path'] = project.fileName()
        context['crs'] = project.crs().authid()
        context['active_layer'] = self.iface.activeLayer()

        # Get layer summaries
        for layer in project.mapLayers().values():
            layer_info = {
                'name': layer.name(),
                'type': type(layer).__name__,
                'feature_count': layer.featureCount() if hasattr(layer, 'featureCount') else None,
                'crs': layer.crs().authid() if hasattr(layer, 'crs') else None
            }
            context['layers'].append(layer_info)

        return context

